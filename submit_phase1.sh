# Cluster : SLURM  |  CPU-only (no GPU needed for Phase 1)
# RESUMABLE: Each stage checks if output already exists and skips if so.
# =============================================================================
#SBATCH --job-name=phase1_nlp
#SBATCH --output=/scratch/nishanth.r/LMA/individual-project-Nishanth-nishu/logs/phase1_%j.log
#SBATCH --error=/scratch/nishanth.r/LMA/individual-project-Nishanth-nishu/logs/phase1_%j.log
#SBATCH --cpus-per-task=5
#SBATCH --mem=20G
#SBATCH --time=4-00:00:00
#SBATCH --partition=plafnet2
#SBATCH --account=plafnet2
#SBATCH --nodelist=gnode118

# =============================================================================
# ?????? CONFIG ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

REPO=/scratch/nishanth.r/LMA/individual-project-Nishanth-nishu
PROJECT=$REPO/project
COMMON=$PROJECT/common/preprocessing
STATS=$PROJECT/common/stats
LOGS=$REPO/logs
VENV=$REPO/venv

FASTTEXT_MODEL=$REPO/lid.176.bin

# Smoke test docs per source (only used in smoke test)
SMOKE_DOCS=500
FULL_RUN=true     # set false to do smoke-test-only dry run

LANGS="hindi nepali"

# =============================================================================
# ?????? HEADER ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

echo "============================================================"
echo "  PHASE 1 ??? Data Collection & Tokenizer Construction"
echo "  Author : Nishanth R  |  CL3-410 Individual Project"
echo "============================================================"
echo "  SLURM_JOB_ID   = $SLURM_JOB_ID"
echo "  SLURM_NODELIST = $SLURM_NODELIST"
echo "  Node           : $(hostname)"
echo "  Started        : $(date)"
echo "============================================================"

# =============================================================================
# ?????? HELPERS ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner() {
    echo ""
    echo "?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????"
    printf  "???  %-59s???\n" "$1"
    echo "?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????"
    echo "  Time: $(date '+%H:%M:%S')"
}

die() {
    echo ""
    echo "[ERROR] $1"
    echo "  Job aborted at: $(date)"
    exit 1
}

# Run a Python stage; abort on failure
run_stage() {
    local stage_label="$1"; shift
    echo "  ??? $stage_label"
    python3 "$@"
    local rc=$?
    if [ $rc -ne 0 ]; then
        die "Stage failed: $stage_label (exit code $rc)"
    fi
    echo "    ??? Done."
}

# Skip a stage if its output file already exists and is non-empty
# Usage: skip_if_done "label" "/path/to/output.jsonl" || { run_stage ... }
skip_if_done() {
    local label="$1"
    local outfile="$2"
    if [ -f "$outfile" ] && [ -s "$outfile" ]; then
        echo "  ??? [SKIP] $label ??? output already exists: $(basename $outfile)"
        return 0   # 0 = skip
    fi
    return 1  # 1 = need to run
}

# =============================================================================
# ?????? STAGE 0: ENVIRONMENT SETUP ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 0: Environment Setup"

mkdir -p "$LOGS"

if [ ! -d "$VENV" ]; then
    echo "  Creating virtualenv at $VENV ???"
    python3 -m venv "$VENV" || die "Failed to create virtualenv"
fi

source "$VENV/bin/activate" || die "Failed to activate virtualenv"
echo "  Python: $(which python3)  ($(python3 --version))"

echo "  Installing dependencies ???"
pip install --quiet --upgrade pip
pip install --quiet \
    datasets \
    sentencepiece \
    datasketch \
    fasttext-wheel \
    langdetect \
    trafilatura \
    pytesseract \
    pdf2image \
    Pillow \
    pyyaml \
    tqdm \
    matplotlib \
    requests
echo "  ??? Dependencies ready."

if [ ! -f "$FASTTEXT_MODEL" ]; then
    echo "  Downloading fastText lid.176.bin (~125 MB) ???"
    wget -q -O "$FASTTEXT_MODEL" \
        "https://dl.fbaipublicfiles.com/fasttext/supervised-models/lid.176.bin" \
        || die "Could not download lid.176.bin"
    echo "  ??? lid.176.bin downloaded."
else
    echo "  ??? lid.176.bin already present."
fi

cd "$PROJECT" || die "Cannot cd to $PROJECT"
export PYTHONPATH="$PROJECT"

# =============================================================================
# ?????? STAGE 0b: SMOKE TEST ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# Validates recon + download work without errors (no test_holdout in smoke).
# =============================================================================

banner "Stage 0b: Smoke Test (${SMOKE_DOCS} docs per source)"

for LANG in $LANGS; do
    echo ""
    echo "  ?????? Smoke: $LANG ??????"

    OUT_RECON="$PROJECT/$LANG/data/source_stats.json"
    if ! skip_if_done "$LANG: recon (sample)" "$OUT_RECON"; then
        run_stage "$LANG: recon (sample)" \
            "$COMMON/recon.py" \
            --lang "$LANG" \
            --repo-root "$PROJECT"
    fi

    # Only smoke-download if no data exists yet (idempotent)
    WIKI_FILE="$PROJECT/$LANG/data/raw/downloaded/${LANG:0:2}_wiki.jsonl"
    if [ "$LANG" = "hindi" ]; then WIKI_FILE="$PROJECT/hindi/data/raw/downloaded/hi_wiki.jsonl"; fi
    if [ "$LANG" = "nepali" ]; then WIKI_FILE="$PROJECT/nepali/data/raw/downloaded/ne_wiki.jsonl"; fi

    if [ -f "$WIKI_FILE" ] && [ -s "$WIKI_FILE" ]; then
        echo "  ??? [SKIP] $LANG: download Wikipedia ??? data already present ($(du -sh $WIKI_FILE | cut -f1))"
    else
        run_stage "$LANG: download Wikipedia (${SMOKE_DOCS} docs)" \
            "$LANG/data/download_public.py" \
            --source wikipedia \
            --max-docs "$SMOKE_DOCS" \
            --repo-root "$PROJECT"
    fi
done

echo ""
echo "  ??? Smoke test passed for all languages."

if [ "$FULL_RUN" != "true" ]; then
    echo ""
    echo "  FULL_RUN=false ??? stopping after smoke test."
    echo "  Set FULL_RUN=true in the script to run the complete pipeline."
    echo "  Job completed: $(date)"
    exit 0
fi

# =============================================================================
# ?????? STAGE 1: SOURCE RECONNAISSANCE ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 1: Source Reconnaissance"

for LANG in $LANGS; do
    echo ""
    echo "  ?????? Recon: $LANG ??????"
    OUT_RECON="$PROJECT/$LANG/data/source_stats.json"
    if ! skip_if_done "$LANG: recon all sources" "$OUT_RECON"; then
        run_stage "$LANG: recon all sources" \
            "$COMMON/recon.py" \
            --lang "$LANG" \
            --repo-root "$PROJECT"
    fi
done

# =============================================================================
# ?????? STAGE 2: RAW ACQUISITION ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 2: Raw Acquisition (Downloaded Corpora)"

for LANG in $LANGS; do
    echo ""
    echo "  ?????? Download: $LANG ??????"

    if [ "$LANG" = "hindi" ]; then
        WIKI_FILE="$PROJECT/hindi/data/raw/downloaded/hi_wiki.jsonl"
    else
        WIKI_FILE="$PROJECT/nepali/data/raw/downloaded/ne_wiki.jsonl"
    fi

    if [ -f "$WIKI_FILE" ] && [ -s "$WIKI_FILE" ]; then
        echo "  ??? [SKIP] $LANG: Wikipedia already downloaded ($(wc -l < $WIKI_FILE) docs)"
    else
        run_stage "$LANG: download all enabled sources" \
            "$PROJECT/$LANG/data/download_public.py" \
            --source all \
            --repo-root "$PROJECT"
    fi
done

# =============================================================================
# ?????? STAGE 3: MANUAL COLLECTION + LLM QUALITY REPAIR (run manually, not here) ??????
# ocr_ingest.py / scrape_ingest.py / transcription_ingest.py need a supplied
# input directory or seed_urls.txt, so they are not looped here. After running
# them for each language, run common/preprocessing/llm_quality_repair.py
# (Yi model) on each manual JSONL to repair OCR/scrape damage BEFORE Stage 4.
# See project/README.md, Step 3b.
# =============================================================================

# =============================================================================
# ?????? STAGE 4: TEST HOLDOUT FREEZE ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# MUST happen before any cleaning. Idempotent: skips if already frozen.
# =============================================================================

banner "Stage 4: Test Holdout ??? Freeze (Before Cleaning)"

for LANG in $LANGS; do
    FROZEN="$PROJECT/$LANG/data/test_holdout/FROZEN.txt"
    if [ -f "$FROZEN" ]; then
        echo "  [$LANG] Holdout already frozen ??? skipping (good)."
    else
        run_stage "$LANG: create + freeze test holdout" \
            "$COMMON/test_holdout.py" \
            --lang "$LANG" \
            --repo-root "$PROJECT"
    fi
done

# =============================================================================
# ?????? STAGES 5???8: CLEANING PIPELINE ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# Per source JSONL: lang_id ??? normalize ??? boilerplate ??? quality_filter
# =============================================================================

banner "Stages 5???8: Cleaning Pipeline (per source, per language)"

for LANG in $LANGS; do
    RAW_DIR="$PROJECT/$LANG/data/raw/downloaded"
    CLEAN_DIR="$PROJECT/$LANG/data/cleaned"
    mkdir -p "$CLEAN_DIR"

    echo ""
    echo "  ?????? Cleaning: $LANG ??????"

    for RAW_JSONL in "$RAW_DIR"/*.jsonl; do
        [ -f "$RAW_JSONL" ] || continue
        BASE=$(basename "$RAW_JSONL" .jsonl)
        echo "    Processing source: $BASE"

        # Stage 5: Language ID
        OUT_LANGID="$CLEAN_DIR/${BASE}_langid.jsonl"
        if ! skip_if_done "$LANG/$BASE: lang_id" "$OUT_LANGID"; then
            run_stage "$LANG/$BASE: lang_id_filter" \
                "$COMMON/lang_id_filter.py" \
                --lang "$LANG" \
                --input  "$RAW_JSONL" \
                --output "$OUT_LANGID" \
                --fasttext-model "$FASTTEXT_MODEL" \
                --repo-root "$PROJECT"
        fi

        # Stage 6: Normalization
        OUT_NORM="$CLEAN_DIR/${BASE}_normalized.jsonl"
        if ! skip_if_done "$LANG/$BASE: normalize" "$OUT_NORM"; then
            run_stage "$LANG/$BASE: normalize" \
                "$COMMON/normalize.py" \
                --lang "$LANG" \
                --input  "$OUT_LANGID" \
                --output "$OUT_NORM" \
                --repo-root "$PROJECT"
        fi

        # Stage 7: Boilerplate removal
        OUT_BPLR="$CLEAN_DIR/${BASE}_boilerplate.jsonl"
        if ! skip_if_done "$LANG/$BASE: boilerplate" "$OUT_BPLR"; then
            run_stage "$LANG/$BASE: boilerplate_strip" \
                "$COMMON/boilerplate_strip.py" \
                --lang "$LANG" \
                --input  "$OUT_NORM" \
                --output "$OUT_BPLR"
        fi

        # Stage 8: Quality filters
        OUT_QUAL="$CLEAN_DIR/${BASE}_quality.jsonl"
        if ! skip_if_done "$LANG/$BASE: quality" "$OUT_QUAL"; then
            run_stage "$LANG/$BASE: quality_filters" \
                "$COMMON/quality_filters.py" \
                --lang "$LANG" \
                --input  "$OUT_BPLR" \
                --output "$OUT_QUAL" \
                --repo-root "$PROJECT"
        fi
    done

    # Merge all per-source quality-filtered files into one
    MERGED="$CLEAN_DIR/all_quality_filtered.jsonl"
    if skip_if_done "$LANG: merged quality" "$MERGED"; then
        :
    else
        echo "  Merging cleaned sources ??? $MERGED"
        cat "$CLEAN_DIR"/*_quality.jsonl > "$MERGED" \
            || die "$LANG: Failed to merge cleaned sources"
        echo "  ??? Merged: $(wc -l < "$MERGED") documents"
    fi
done

# =============================================================================
# ?????? STAGE 10: EXACT DEDUPLICATION ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 10: Exact Deduplication (SHA-256)"

for LANG in $LANGS; do
    CLEAN_DIR="$PROJECT/$LANG/data/cleaned"
    DEDUP_DIR="$PROJECT/$LANG/data/dedup"
    mkdir -p "$DEDUP_DIR"
    OUT="$DEDUP_DIR/exact_deduped.jsonl"
    if ! skip_if_done "$LANG: dedup_exact" "$OUT"; then
        run_stage "$LANG: dedup_exact" \
            "$COMMON/dedup_exact.py" \
            --lang "$LANG" \
            --input  "$CLEAN_DIR/all_quality_filtered.jsonl" \
            --output "$OUT"
    fi
done

# =============================================================================
# ?????? STAGE 11: PARAGRAPH DEDUPLICATION ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 11: Paragraph-level Deduplication"

for LANG in $LANGS; do
    DEDUP_DIR="$PROJECT/$LANG/data/dedup"
    OUT="$DEDUP_DIR/para_deduped.jsonl"
    if ! skip_if_done "$LANG: dedup_paragraph" "$OUT"; then
        run_stage "$LANG: dedup_paragraph" \
            "$COMMON/dedup_paragraph.py" \
            --lang "$LANG" \
            --input  "$DEDUP_DIR/exact_deduped.jsonl" \
            --output "$OUT" \
            --repo-root "$PROJECT"
    fi
done

# =============================================================================
# ?????? STAGE 12: NEAR-DEDUPLICATION ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 12: Near-Deduplication (MinHash + LSH)"

for LANG in $LANGS; do
    DEDUP_DIR="$PROJECT/$LANG/data/dedup"
    OUT="$DEDUP_DIR/near_deduped.jsonl"
    if ! skip_if_done "$LANG: dedup_near" "$OUT"; then
        run_stage "$LANG: dedup_near" \
            "$COMMON/dedup_near.py" \
            --lang "$LANG" \
            --input  "$DEDUP_DIR/para_deduped.jsonl" \
            --output "$OUT"
    fi
done

# =============================================================================
# ?????? STAGE 13: SEMANTIC / SAFETY FILTER ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 13: Semantic / Safety Filter (Conservative)"

for LANG in $LANGS; do
    DEDUP_DIR="$PROJECT/$LANG/data/dedup"
    OUT="$DEDUP_DIR/safety_filtered.jsonl"
    if ! skip_if_done "$LANG: safety_filter" "$OUT"; then
        run_stage "$LANG: semantic_safety_filter" \
            "$COMMON/semantic_safety_filter.py" \
            --lang "$LANG" \
            --input  "$DEDUP_DIR/near_deduped.jsonl" \
            --output "$OUT" \
            --repo-root "$PROJECT"
    fi
    echo "  ???  Audit rejected docs: $DEDUP_DIR/rejected_${LANG}.jsonl"
done

# =============================================================================
# ?????? STAGE 14: DECONTAMINATION ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 14: Decontamination Against Frozen Test Set"

for LANG in $LANGS; do
    DEDUP_DIR="$PROJECT/$LANG/data/dedup"
    DECONTAM_DIR="$PROJECT/$LANG/data/decontaminated"
    TEST_HOLDOUT="$PROJECT/$LANG/data/test_holdout/test.jsonl"
    mkdir -p "$DECONTAM_DIR"
    OUT="$DECONTAM_DIR/decontaminated.jsonl"

    if [ ! -f "$TEST_HOLDOUT" ]; then
        die "$LANG: test_holdout/test.jsonl missing ??? did Stage 4 complete?"
    fi

    if ! skip_if_done "$LANG: decontaminate" "$OUT"; then
        run_stage "$LANG: decontaminate" \
            "$COMMON/decontaminate.py" \
            --lang "$LANG" \
            --input       "$DEDUP_DIR/safety_filtered.jsonl" \
            --test-holdout "$TEST_HOLDOUT" \
            --output      "$OUT" \
            --repo-root   "$PROJECT"
    fi
done

# =============================================================================
# ?????? STAGE 16: TRAIN / VALIDATION SPLITS ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stage 16: Train / Validation Splits"

for LANG in $LANGS; do
    SPLITS_DIR="$PROJECT/$LANG/data/splits"
    mkdir -p "$SPLITS_DIR"
    OUT="$SPLITS_DIR/train.jsonl"
    DECONTAM_DIR="$PROJECT/$LANG/data/decontaminated"

    if ! skip_if_done "$LANG: split" "$OUT"; then
        run_stage "$LANG: split_data" \
            "$COMMON/split_data.py" \
            --lang "$LANG" \
            --input "$DECONTAM_DIR/decontaminated.jsonl" \
            --repo-root "$PROJECT"
    fi
done

# =============================================================================
# ?????? STAGES 17???18: TOKENIZER TRAINING + VOCAB SWEEP ?????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Stages 17???18: Tokenizer Training + Vocabulary Sweep"

for LANG in $LANGS; do
    VOCAB_DIR="$PROJECT/$LANG/tokenizer/vocab"
    TRAIN_JSONL="$PROJECT/$LANG/data/splits/train.jsonl"

    if [ ! -f "$TRAIN_JSONL" ]; then
        die "$LANG: splits/train.jsonl missing ??? did Stage 16 complete?"
    fi

    # Check if a model already exists
    EXISTING_MODEL=$(ls "$VOCAB_DIR"/*.model 2>/dev/null | head -1)
    if [ -n "$EXISTING_MODEL" ]; then
        echo "  ??? [SKIP] $LANG: tokenizer ??? model already exists: $(basename $EXISTING_MODEL)"
    else
        run_stage "$LANG: train_tokenizer (vocab sweep)" \
            "$COMMON/train_tokenizer.py" \
            --lang "$LANG" \
            --repo-root "$PROJECT"
    fi
done

# =============================================================================
# ?????? FINAL: STATISTICS + PLOTS + REPORT ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

banner "Final: Statistics, Plots & Report Generation"

HINDI_STATS="$PROJECT/hindi/data/stats.json"
NEPALI_STATS="$PROJECT/nepali/data/stats.json"
FIGURES_DIR="$PROJECT/report/figures"
mkdir -p "$FIGURES_DIR"

run_stage "compute_stats: hindi" \
    "$STATS/compute_stats.py" \
    --lang hindi \
    --repo-root "$PROJECT" \
    --output "$HINDI_STATS"

run_stage "compute_stats: nepali" \
    "$STATS/compute_stats.py" \
    --lang nepali \
    --repo-root "$PROJECT" \
    --output "$NEPALI_STATS"

run_stage "plots" \
    "$STATS/plots.py" \
    --hindi-stats  "$HINDI_STATS" \
    --nepali-stats "$NEPALI_STATS" \
    --output-dir   "$FIGURES_DIR"

run_stage "generate_report" \
    "$STATS/generate_report.py" \
    --hindi-stats  "$HINDI_STATS" \
    --nepali-stats "$NEPALI_STATS" \
    --figures-dir  "$FIGURES_DIR" \
    --output       "$PROJECT/report/phase1_report.md" \
    --repo-root    "$PROJECT"

# =============================================================================
# ?????? FOOTER ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# =============================================================================

echo ""
echo "============================================================"
echo "  Phase 1 Pipeline ??? COMPLETE"
echo "  Author  : Nishanth R"
echo "  Ended   : $(date)"
echo "============================================================"
echo ""
echo "  Outputs:"
echo "    Hindi tokenizer  : $PROJECT/hindi/tokenizer/vocab/"
echo "    Nepali tokenizer : $PROJECT/nepali/tokenizer/vocab/"
echo "    Phase 1 report   : $PROJECT/report/phase1_report.md"
echo "    Figures          : $PROJECT/report/figures/"
echo "    Hindi manifest   : $PROJECT/hindi/data/manifest.csv"
echo "    Nepali manifest  : $PROJECT/nepali/data/manifest.csv"
echo ""
echo "  ???  Manual actions still required:"
echo "    1. Fill in null thresholds in filtering_thresholds.yaml"
echo "       (run recon.py --inspect-feature for each feature)"
echo "    2. Set final_vocab_size in tokenizer_config.yaml (both languages)"
echo "    3. Fill in <!-- TODO --> sections in phase1_report.md"
echo "    4. Audit rejected docs: data/dedup/rejected_*.jsonl"
echo ""
echo "  Log: $LOGS/phase1_${SLURM_JOB_ID}.log"
echo "============================================================"
