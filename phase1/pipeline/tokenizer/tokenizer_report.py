"""
tokenizer_report.py
===================
Produces the per-language tokenizer statistics the brief explicitly asks for:

    "Report, for each language: vocabulary size, token-frequency statistics,
     average characters per token, tokenization examples, and unknown-token
     statistics."

v1 computed only fertility and UNK rate. `tokenizer_config.yaml` listed
`avg_chars_per_token` and `compression_ratio` under sweep metrics, but nothing
computed them, so those two deliverables were unmet.

This script reads the FINAL tokenizer and the held-out split and emits:

  <lang>/tokenizer/analysis/token_stats.json     machine-readable, for the report
  <lang>/tokenizer/analysis/token_frequency.csv  full frequency table
  <lang>/tokenizer/analysis/examples.md          side-by-side segmentations

Definitions used, and why
-------------------------
fertility            tokens / whitespace-word on held-out text. The standard
                     intrinsic metric (Rust et al., ACL 2021). Lower is better;
                     1.0 would mean one token per word.

chars_per_token      mean characters per emitted token. Reported alongside
                     bytes_per_token because for Devanagari the two differ by
                     ~3x (most codepoints are 3 UTF-8 bytes), and a tokenizer
                     that looks efficient per character can still be expensive
                     per byte.

byte_fallback_rate   share of emitted tokens that are raw <0xNN> byte pieces.
                     With byte_fallback=True the UNK rate is structurally zero,
                     so UNK alone no longer discriminates. Stranded single
                     bytes are what actually drive the token-inflation penalty
                     on Indic scripts, so this is the number to watch.

vocab utilisation    share of the vocabulary that ever fires on held-out text,
                     plus the share of held-out tokens covered by the top 1k /
                     10k pieces. A vocabulary where 40% of pieces never appear
                     is 40% wasted embedding parameters, and that is worth
                     saying out loud in a report.

Zipf slope           fitted exponent of the rank-frequency law. A healthy
                     subword vocabulary sits near -1. Sharp deviation usually
                     means the corpus is dominated by one source or by
                     boilerplate that survived cleaning.

Usage
-----
  python tokenizer_report.py --lang hindi  --repo-root /path/to/project
  python tokenizer_report.py --lang nepali --repo-root /path/to/project
"""

