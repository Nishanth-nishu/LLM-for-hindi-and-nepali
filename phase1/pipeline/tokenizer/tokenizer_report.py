def _is_byte_piece(p: str) -> bool:
    return len(p) == 6 and p.startswith("<0x") and p.endswith(">")


def sample_docs(jsonl_path: Path, *, text_key="text", n=20000, seed=20260820,
                provenance_key="provenance_class"):
    rng = random.Random(seed)
    res, buckets, seen = [], {}, 0
    with open(jsonl_path, encoding="utf-8") as f:
        for raw in f:
            raw = raw.strip()
            if not raw:
                continue
            try:
                doc = json.loads(raw)
            except json.JSONDecodeError:
                continue
            t = doc.get(text_key) or ""
            if not t.strip():
                continue
            seen += 1
            if len(res) < n:
                res.append(t)
            else:
                j = rng.randrange(seen)
                if j < n:
                    res[j] = t
            cls = doc.get(provenance_key)
            if cls:
                b = buckets.setdefault(str(cls), [])
                if len(b) < n // 2:
                    b.append(t)
    return res, buckets


def zipf_slope(freqs: list[int], max_rank: int = 5000) -> float:
    """Least-squares slope of log(freq) on log(rank). ~-1 is a healthy vocabulary."""
    pts = [(math.log(r + 1), math.log(f))
           for r, f in enumerate(freqs[:max_rank]) if f > 0]
    if len(pts) < 10:
        return float("nan")
    n = len(pts)
    sx = sum(x for x, _ in pts)
    sy = sum(y for _, y in pts)
    sxx = sum(x * x for x, _ in pts)
    sxy = sum(x * y for x, y in pts)
    denom = n * sxx - sx * sx
    return (n * sxy - sx * sy) / denom if denom else float("nan")


def analyse(sp, texts: list[str], buckets: dict) -> dict:
    vocab_size = sp.get_piece_size()
    unk_id = sp.unk_id()

    counts: Counter[int] = Counter()
    tot_pieces = tot_words = tot_chars = tot_bytes = 0
    n_unk = n_bytefb = 0
    docs_with_unk = 0
    piece_len_hist: Counter[int] = Counter()

    for text in texts:
        words = text.split()
        if not words:
            continue
        ids = sp.encode(text, out_type=int)
        if not ids:
            continue
        counts.update(ids)
        tot_pieces += len(ids)
        tot_words += len(words)
        tot_chars += len(text)
        tot_bytes += len(text.encode("utf-8"))
        d_unk = sum(1 for t in ids if t == unk_id)
        n_unk += d_unk
        if d_unk:
            docs_with_unk += 1
        for i in ids:
            p = sp.id_to_piece(i)
            if _is_byte_piece(p):
                n_bytefb += 1
            piece_len_hist[len(p.replace("???", ""))] += 1

    if tot_pieces == 0:
        raise RuntimeError("no tokens produced -- is the eval split empty?")

    ranked = counts.most_common()
    freqs = [c for _, c in ranked]
    used = len(counts)

    def coverage(k: int) -> float:
        return sum(freqs[:k]) / tot_pieces

    hapax = sum(1 for c in freqs if c == 1)

    return {
        "vocabulary": {
            "vocab_size": vocab_size,
            "pieces_observed_on_heldout": used,
            "vocab_utilisation": round(used / vocab_size, 4),
            "unused_pieces": vocab_size - used,
            "hapax_pieces_on_heldout": hapax,
        },
        "efficiency": {
            "fertility_tokens_per_word": round(tot_pieces / tot_words, 4),
            "avg_chars_per_token": round(tot_chars / tot_pieces, 4),
            "avg_bytes_per_token": round(tot_bytes / tot_pieces, 4),
            "compression_ratio_bytes_per_token": round(tot_bytes / tot_pieces, 4),
            "avg_tokens_per_document": round(tot_pieces / len(texts), 2),
        },
        "unknown_tokens": {
            "unk_token_id": unk_id,
            "unk_count": n_unk,
            "unk_rate": round(n_unk / tot_pieces, 8),
            "documents_containing_unk": docs_with_unk,
            "document_unk_rate": round(docs_with_unk / len(texts), 6),
            "byte_fallback_count": n_bytefb,
            "byte_fallback_rate": round(n_bytefb / tot_pieces, 8),
            "note": ("With byte_fallback enabled the UNK rate is structurally "
                     "zero: any unseen character decomposes into UTF-8 byte "
                     "pieces rather than becoming UNK. byte_fallback_rate is "
                     "the meaningful successor metric -- stranded single bytes "
                     "are what drive token inflation on Devanagari."),
        },
        "token_frequency": {
            "total_tokens_evaluated": tot_pieces,
            "coverage_top_100": round(coverage(100), 4),
            "coverage_top_1000": round(coverage(1000), 4),
            "coverage_top_10000": round(coverage(10000), 4),
            "zipf_slope": round(zipf_slope(freqs), 4),
            "most_frequent": [
                {"piece": sp.id_to_piece(i), "id": i, "count": c,
                 "share": round(c / tot_pieces, 6)}
                for i, c in ranked[:30]
            ],
            "piece_length_histogram_chars": dict(sorted(piece_len_hist.items())[:20]),
        },
        "fertility_by_provenance": {
            cls: round(
                sum(len(sp.encode(t, out_type=int)) for t in bt)
                / max(1, sum(len(t.split()) for t in bt)), 4)
            for cls, bt in buckets.items() if len(bt) >= 20
        },
        "_ranked_for_csv": ranked,
    }


def write_examples(sp, lang: str, out_path: Path, extra: list[str] | None = None):
    probes = list(DEFAULT_PROBES.get(lang, []))
    if extra:
        probes += extra
    lines = [f"# Tokenization examples ??? {lang}", "",
             "Produced by `tokenizer_report.py` from the final tokenizer. "
             "`???` marks a word boundary (SentencePiece's space marker); "
             "`<0xNN>` pieces are byte fallbacks.", ""]
    for i, s in enumerate(probes, 1):
        pieces = sp.encode(s, out_type=str)
        ids = sp.encode(s, out_type=int)
        n_words = len(s.split())
        lines += [
            f"### Example {i}", "",
            f"**Input** ({len(s)} chars, {n_words} words):", "",
            f"```\n{s}\n```", "",
            f"**Tokens** ({len(pieces)} pieces, fertility "
            f"{len(pieces) / max(1, n_words):.2f}):", "",
            "```\n" + " | ".join(pieces) + "\n```", "",
            f"**IDs:** `{ids}`", "",
            f"**Round-trip exact:** {'yes' if sp.decode(ids) == s else 'NO ??? investigate'}",
            "", "---", "",
        ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[2],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lang", required=True)
    ap.add_argument("--repo-root", default=".")
    ap.add_argument("--model", default=None,
                    help="defaults to <lang>/tokenizer/vocab/<lang>_tokenizer.model")
    ap.add_argument("--split", default="test",
                    choices=["val", "test", "train"],
                    help="which held-out split to report on")
    ap.add_argument("--sample", type=int, default=20000)
    ap.add_argument("--text-key", default="text")
    ap.add_argument("--seed", type=int, default=20260820)
    args = ap.parse_args()

    import sentencepiece as spm

    root = Path(args.repo_root).resolve()
    lang = args.lang
    model_path = Path(args.model) if args.model else \
        root / lang / "tokenizer" / "vocab" / f"{lang}_tokenizer.model"
    if not model_path.exists():
        print(f"[error] tokenizer not found: {model_path}\n"
              f"        run train_tokenizer.py --lang {lang} first", file=sys.stderr)
        return 1

    split_path = root / lang / "data" / "splits" / f"{args.split}.jsonl"
    if not split_path.exists():
        print(f"[error] split not found: {split_path}", file=sys.stderr)
        return 1

    sp = spm.SentencePieceProcessor()
    sp.load(str(model_path))

    print(f"[{lang}] tokenizer={model_path.name} vocab={sp.get_piece_size()} "
          f"split={args.split}")
    texts, buckets = sample_docs(split_path, text_key=args.text_key,
                                 n=args.sample, seed=args.seed)
    print(f"  sampled {len(texts):,} held-out documents")
    if buckets:
        print(f"  provenance buckets: { {k: len(v) for k, v in buckets.items()} }")
    else:
        print("  [note] no `provenance_class` field found -- manual vs downloaded "
              "fertility cannot be reported. Add it in manifest_utils.py.")

    stats = analyse(sp, texts, buckets)
    ranked = stats.pop("_ranked_for_csv")

    analysis_dir = root / lang / "tokenizer" / "analysis"
    analysis_dir.mkdir(parents=True, exist_ok=True)

    stats["meta"] = {
        "language": lang,
        "model_file": str(model_path),
        "evaluated_split": args.split,
        "documents_sampled": len(texts),
        "sample_seed": args.seed,
    }
    out_json = analysis_dir / "token_stats.json"
    out_json.write_text(json.dumps(stats, ensure_ascii=False, indent=2),
                        encoding="utf-8")

    freq_csv = analysis_dir / "token_frequency.csv"
    with open(freq_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["rank", "id", "piece", "count", "share", "is_byte_fallback"])
        total = stats["token_frequency"]["total_tokens_evaluated"]
        for r, (i, c) in enumerate(ranked, 1):
            p = sp.id_to_piece(i)
            w.writerow([r, i, p, c, f"{c / total:.8f}", int(_is_byte_piece(p))])

    ex_md = analysis_dir / "examples.md"
    write_examples(sp, lang, ex_md)

    e, u, v = stats["efficiency"], stats["unknown_tokens"], stats["vocabulary"]
    print(f"\n  fertility            {e['fertility_tokens_per_word']}")
    print(f"  chars/token          {e['avg_chars_per_token']}")
    print(f"  bytes/token          {e['avg_bytes_per_token']}")
    print(f"  unk rate             {u['unk_rate']:.8f}")
    print(f"  byte-fallback rate   {u['byte_fallback_rate']:.8f}")
    print(f"  vocab utilisation    {v['vocab_utilisation']:.1%} "
          f"({v['unused_pieces']:,} pieces never fire)")
    print(f"  zipf slope           {stats['token_frequency']['zipf_slope']}")
    if stats["fertility_by_provenance"]:
        print(f"  fertility by source  {stats['fertility_by_provenance']}")
    if v["vocab_utilisation"] < 0.5:
        print(f"\n  [WARN] over half the vocabulary never fires on held-out text. "
              f"That is embedding parameters bought and not used -- consider a "
              f"smaller vocabulary, and say so in the report.")
    print(f"\n  wrote {out_json}\n        {freq_csv}\n        {ex_md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
