"""
split_data.py  (v2)
--------------------
Stage 16: Train / Validation splits.

The test set is ALREADY FROZEN from stage 4.  This script only splits
the post-decontamination training candidate pool into train and val.

Key invariants
--------------
  - Reads split ratios from data_config.yaml (train_ratio, val_ratio).
  - Document-level split ONLY ??? never sentence-level.
  - Stratified by collection_method to preserve manual/downloaded proportions.
  - Writes splits/split_manifest.csv: doc_id ??? split mapping.
  - Writes splits/train.jsonl and splits/val.jsonl.
  - Copies test_holdout/test.jsonl ??? splits/test.jsonl (read-only copy).

Usage
-----
  python split_data.py \\
      --lang hindi \\
      --input hindi/data/decontaminated/decontaminated.jsonl \\
      --repo-root .
"""

import argparse
import csv
import json
import random
import shutil
import sys
from collections import defaultdict
from pathlib import Path

import yaml
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "common" / "preprocessing"))
from manifest_utils import load_manifest, update_rows


def stratified_split(
    doc_ids: list[str],
    doc_to_method: dict[str, str],
    train_ratio: float,
    val_ratio: float,
    seed: int,
) -> dict[str, list[str]]:
    """
    Stratify doc_ids by collection_method and split into train/val.

    Parameters
    ----------
    doc_ids : list[str]
    doc_to_method : dict[str, str]
    train_ratio : float
    val_ratio : float
    seed : int

    Returns
    -------
    dict[str, list[str]]
        {'train': [...], 'val': [...]}
    """
    rng = random.Random(seed)
    strata: dict[str, list[str]] = defaultdict(list)
    for doc_id in doc_ids:
        method = doc_to_method.get(doc_id, "downloaded")
        strata[method].append(doc_id)

    train_ids: list[str] = []
    val_ids:   list[str] = []

    for stratum in strata.values():
        rng.shuffle(stratum)
        n_val   = max(1, int(len(stratum) * val_ratio))
        val_ids.extend(stratum[:n_val])
        train_ids.extend(stratum[n_val:])

    return {"train": train_ids, "val": val_ids}


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Stage 16: Train/val split (test already frozen).",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--lang", required=True, choices=["hindi", "nepali"])
    parser.add_argument("--input", required=True,
                        help="Decontaminated training candidate JSONL.")
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--text-key", default="text")
    return parser.parse_args()


def main() -> None:
    """Read config, split docs, write train/val JSONL + split manifest."""
    args = parse_args()
    repo_root = Path(args.repo_root).resolve()
    lang = args.lang

    config_path = repo_root / lang / "configs" / "data_config.yaml"
    with open(config_path, "r", encoding="utf-8") as f:
        config = yaml.safe_load(f)

    splits_cfg  = config.get("splits", {})
    train_ratio = splits_cfg.get("train_ratio", 0.96)
    val_ratio   = splits_cfg.get("val_ratio", 0.04)
    seed        = splits_cfg.get("seed", 42)

    splits_dir = repo_root / lang / "data" / "splits"
    splits_dir.mkdir(parents=True, exist_ok=True)

    # doc_id ??? collection_method from manifest
    manifest_rows  = load_manifest(lang, str(repo_root))
    doc_to_method  = {r["doc_id"]: r.get("collection_method", "downloaded")
                      for r in manifest_rows}

    # ?????? Collect doc_ids from input ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    print(f"[split_data] Collecting doc_ids from {args.input}???")
    all_doc_ids: list[str] = []
    with open(args.input, "r", encoding="utf-8") as f:
        for line in tqdm(f, desc="reading", unit="doc"):
            line = line.strip()
            if not line:
                continue
            try:
                doc = json.loads(line)
                all_doc_ids.append(str(doc.get("doc_id", "")))
            except json.JSONDecodeError:
                continue

    print(f"  Total training candidates: {len(all_doc_ids):,}")

    # ?????? Stratified split ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    split_assignment = stratified_split(
        all_doc_ids, doc_to_method, train_ratio, val_ratio, seed
    )
    train_set = set(split_assignment["train"])
    val_set   = set(split_assignment["val"])

    # ?????? Write JSONL files ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    handles = {
        "train": open(splits_dir / "train.jsonl", "w", encoding="utf-8"),
        "val":   open(splits_dir / "val.jsonl",   "w", encoding="utf-8"),
    }
    counts: dict[str, int] = {"train": 0, "val": 0}

    with open(args.input, "r", encoding="utf-8") as fin:
        for line in tqdm(fin, desc="writing splits", unit="doc"):
            line = line.strip()
            if not line:
                continue
            try:
                doc = json.loads(line)
            except json.JSONDecodeError:
                continue
            doc_id = str(doc.get("doc_id", ""))
            if doc_id in train_set:
                handles["train"].write(json.dumps(doc, ensure_ascii=False) + "\n")
                counts["train"] += 1
            elif doc_id in val_set:
                handles["val"].write(json.dumps(doc, ensure_ascii=False) + "\n")
                counts["val"] += 1

    for fh in handles.values():
        fh.close()

    # ?????? Copy frozen test ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    test_src = repo_root / lang / "data" / "test_holdout" / "test.jsonl"
    test_dst = splits_dir / "test.jsonl"
    if test_src.exists():
        shutil.copy(test_src, test_dst)
        print(f"[split_data] Copied frozen test -> {test_dst}")
    else:
        print(f"[split_data] WARNING: test_holdout/test.jsonl not found.", file=sys.stderr)

    # ?????? Write split_manifest.csv ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    split_manifest_path = splits_dir / "split_manifest.csv"
    with open(split_manifest_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["doc_id", "split", "collection_method"])
        writer.writeheader()
        for split_name, ids in split_assignment.items():
            for doc_id in ids:
                writer.writerow({
                    "doc_id": doc_id,
                    "split":  split_name,
                    "collection_method": doc_to_method.get(doc_id, "downloaded"),
                })

    # ?????? Update manifest split field ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    split_updates = {}
    for split_name, ids in split_assignment.items():
        for doc_id in ids:
            split_updates[doc_id] = {"split": split_name}
    n = update_rows(lang, split_updates, str(repo_root))
    print(f"[split_data] Updated {n} manifest rows with split assignments.")

    # ?????? Summary ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    print(f"\n[split_data] Done.")
    for split_name, count in counts.items():
        manual = sum(1 for d in split_assignment[split_name]
                     if doc_to_method.get(d) == "manual")
        print(f"  {split_name:6s}: {count:8,} docs  (manual={manual:,}, "
              f"downloaded={count-manual:,})")


if __name__ == "__main__":
    main()
