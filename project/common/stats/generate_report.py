def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Render phase1_report.md from pre-computed stats.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--hindi-stats",  required=True)
    parser.add_argument("--nepali-stats", required=True)
    parser.add_argument("--figures-dir",  default="report/figures/")
    parser.add_argument("--output",       default="report/phase1_report.md")
    parser.add_argument("--repo-root",    default=".")
    return parser.parse_args()


def main() -> None:
    """Load stats and render the Phase 1 markdown report."""
    args = parse_args()
    repo_root   = Path(args.repo_root).resolve()
    figures_dir = Path(args.figures_dir)

    sh = _load(args.hindi_stats)
    sn = _load(args.nepali_stats)

    report_md = render_report(sh, sn, figures_dir, repo_root)

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(report_md)

    print(f"[generate_report] Phase 1 report written -> {out_path}")
    print("  Fill in all <!-- TODO --> sections before submission.")


if __name__ == "__main__":
    main()
