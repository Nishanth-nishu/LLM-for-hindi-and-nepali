from pathlib import Path


def _load(path: str) -> dict:
    """Load a stats JSON file, returning {} on failure."""
    p = Path(path)
    if not p.exists():
        print(f"[generate_report] WARNING: {p} not found. Report will have gaps.", file=sys.stderr)
        return {}
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)


def _fmt_int(v) -> str:
    """Format an integer with commas."""
    try:
        return f"{int(v):,}"
    except (TypeError, ValueError):
        return str(v) if v is not None else "N/A"


def _fmt_float(v, decimals=2) -> str:
    try:
        return f"{float(v):.{decimals}f}"
    except (TypeError, ValueError):
        return str(v) if v is not None else "N/A"


def render_filter_table(filter_table: list) -> str:
    """Render the stage-by-stage filtering table as markdown."""
    header = (
        "| Stage | Docs In | Docs Dropped | Tokens In (est.) | Tokens Dropped (est.) |\n"
        "|---|---|---|---|---|\n"
    )
    rows = ""
    for r in filter_table:
        rows += (
            f"| {r.get('stage', '')} "
            f"| {_fmt_int(r.get('docs_in', 0))} "
            f"| {_fmt_int(r.get('docs_dropped', 0))} "
            f"| {_fmt_int(r.get('tokens_in_est', 0))} "
            f"| {_fmt_int(r.get('tokens_dropped_est', 0))} |\n"
        )
    return header + rows


def render_source_table(source_table: list) -> str:
    """Render the per-source statistics table as markdown."""
    header = (
        "| Source | Raw Docs | Raw Tokens (est.) | Final Docs | Final Tokens (est.) | Manual? |\n"
        "|---|---|---|---|---|---|\n"
    )
    rows = ""
    for r in source_table:
        rows += (
            f"| {r.get('source_name', '')} "
            f"| {_fmt_int(r.get('raw_docs', 0))} "
            f"| {_fmt_int(r.get('raw_tokens_est', 0))} "
            f"| {_fmt_int(r.get('final_docs', 0))} "
            f"| {_fmt_int(r.get('final_tokens_est', 0))} "
            f"| {r.get('manual', 'No')} |\n"
        )
    return header + rows


def render_sweep_table(sweep: list) -> str:
    """Render the vocabulary sweep comparison table."""
    header = (
        "| Vocab Size | Fertility | Avg Chars/Token | UNK Rate (%) | Compression Ratio |\n"
        "|---|---|---|---|---|\n"
    )
    rows = ""
    for r in sweep:
        rows += (
            f"| {_fmt_int(r.get('vocab_size', ''))} "
            f"| {_fmt_float(r.get('fertility', ''))} "
            f"| {_fmt_float(r.get('avg_chars_per_token', r.get('avg_chars', '')))} "
            f"| {_fmt_float(float(r.get('unk_rate', 0)) * 100, 4)} "
            f"| {_fmt_float(r.get('compression_ratio', ''))} |\n"
        )
    return header + rows


def render_examples(examples: list) -> str:
    """Render tokenization examples as a markdown list."""
    if not examples:
        return "_No examples available._\n"
    lines = []
    for i, ex in enumerate(examples[:5], 1):
        orig   = ex.get("original", "")
        tokens = ex.get("tokens", [])
        n      = ex.get("n_tokens", len(tokens))
        lines.append(f"{i}. **Input:** {orig}")
        lines.append(f"   **Tokens ({n}):** `{'` `'.join(str(t) for t in tokens)}`")
        lines.append("")
    return "\n".join(lines)


